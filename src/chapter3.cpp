void checkpoint(int place) {
	platform::system_color(0xC7);
	std::cout << "已进入检查点\nA.继续游戏\nB.回到开始菜单（选择章节）\nC.关闭游戏\n";
	while (1) {
		key = getch();
		ingame = false;
		if (key == 'A' || key == 'a') {
			pause_game(1); break;
		}
		else if (key == 'B' || key == 'b') {
			ingame = true;
			pause_game(1);
			break;
		}
		else if (key == 'C' || key == 'c') {
			break;
		}
	}
	if (ingame == false) {
		if (place == 0) city();
		else hell();
	}
}

