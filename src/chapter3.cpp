int s21 = 1;
bool n = false, s = false, e = false, w = false;


void reborn() {
	s21 = 1;
	n = false; s = false; e = false; w = false;
}

void where() {
	reborn();
	std::cout << "你要去哪里？（按N/S/W/E选择）\n";
	while (1) {
		if (s21 == 4 + 1) break;
		if (s21 == 1) {
			if (rooms.count(Prooms + 1) > 0) {
				std::cout << "N.向北走\n"; n = true;
			}
		}
		else if (s21 == 2) {
			if (rooms.count(Prooms - 1) > 0) {
				std::cout << "S.向南走\n"; s = true;
			}
		}
		else if (s21 == 3) {
			if (rooms.count(Prooms - 0.1) > 0) {
				std::cout << "W.向西走\n"; w = true;
			}
		}
		else if (s21 == 4) {
			if (rooms.count(Prooms + 0.1) > 0) {
				std::cout << "E.向东走\n"; e = true;
			}
		}
		s21++;
	}
	while (1) {
		key = getch();
		if (key == 'N' || key == 'n') {
			if (n == true) {
				Prooms++;
				text("你向北走……（按任意键继续）", 1);
				break;
			}
		}
		else if (key == 'S' || key == 's') {
			if (s == true) {
				Prooms = Prooms - 1;
				text("你向南走……（按任意键继续）", 1);
				break;
			}
		}
		else if (key == 'W' || key == 'w') {
			if (w == true) {
				Prooms = Prooms - 0.1;
				text("你向西走……（按任意键继续）", 1);
				break;
			}
		}
		else if (key == 'E' || key == 'e') {
			if (e == true) {
				Prooms = Prooms + 0.1;
				text("你向东走……（按任意键继续）", 1);
				break;
			}
		}
	}
}

